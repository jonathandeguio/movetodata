package io.movetodata.catalog.library.models;

import lombok.*;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import javax.persistence.*;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

/**
 * A Data Product entry in the native Data Catalog.
 *
 * {@code dataProductType}: SOURCE_ALIGNED | AGGREGATE | CONSUMER_ALIGNED
 * {@code accessPolicy}:    PUBLIC | INTERNAL | RESTRICTED
 * {@code qualityLevel}:    BRONZE | SILVER | GOLD
 */
@Entity
@NoArgsConstructor
@AllArgsConstructor
@Getter
@Setter
@Builder
@Table(name = "catalog_data_product")
public class DataProduct {

    /** UUID primary key — generated by PostgreSQL gen_random_uuid(). */
    @Id
    @Column(name = "id", columnDefinition = "uuid", updatable = false, nullable = false)
    private String id;

    @Column(name = "name", nullable = false, unique = true, length = 255)
    private String name;

    @Column(name = "display_name", length = 255)
    private String displayName;

    @Column(name = "description")
    private String description;

    @Column(name = "data_product_type", length = 50)
    private String dataProductType;

    @Column(name = "access_policy", length = 20)
    private String accessPolicy;

    @Column(name = "quality_level", length = 10)
    private String qualityLevel;

    @Column(name = "trust_score", precision = 5, scale = 2)
    private BigDecimal trustScore;

    @Column(name = "domain_id", columnDefinition = "uuid")
    private String domainId;

    @Column(name = "owner_id", columnDefinition = "uuid")
    private UUID ownerId;

    /** JSON array string of use-case labels. */
    @Column(name = "use_cases", columnDefinition = "TEXT")
    private String useCases;

    @Column(name = "steward_id", columnDefinition = "uuid")
    private UUID stewardId;

    /** Source of the description: 'manual' | 'ai' | 'imported'. */
    @Column(name = "description_source", length = 50)
    private String descriptionSource;

    /** Whether the access policy is inherited from the parent domain. */
    @Column(name = "policy_inherited")
    private Boolean policyInherited;

    /** Cumulative number of views (incremented on each data-product page load). */
    @Column(name = "view_count")
    private Long viewCount;

    /** Type de source de données : ex. "PostgreSQL", "Kafka", "S3", "dbt", etc. */
    @Column(name = "source_type", length = 100)
    private String sourceType;

    /**
     * Score de confiance minimum pour l'obtention de la certification Gold (défaut : 80).
     * Utilisé par {@link io.movetodata.catalog.library.services.CatalogCertificationService}.
     */
    @Column(name = "gold_threshold")
    private Integer goldThreshold;

    @Column(name = "created_by", nullable = false, columnDefinition = "uuid")
    private UUID createdBy;

    @CreationTimestamp
    @Column(name = "created_at", updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at")
    private Instant updatedAt;
}
